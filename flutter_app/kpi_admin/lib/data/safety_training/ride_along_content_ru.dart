// Содержание обучения Ride Along — русская версия.
//
// «Ride Along» — это двухдневная сопровождаемая поездка для новых
// водителей: день 1 с меньшим числом стопов, день 2 — заметно больше.
// Тренер при этом проходит контрольный лист, подписывает каждый пункт и
// в конце даёт обратную связь; лист сдаётся в виде фотографии
// ответственному диспетчеру.
//
// Цель этого обучения: ПОДГОТОВКА. Кто пройдёт его заранее, услышит темы
// этих двух дней не в первый раз, а сможет задавать точные вопросы и
// осознанно использовать сопровождаемую поездку.
//
// Структура как в Green Book: в каждой главе несколько слайдов из
// типизированных блоков — плитки с числами, разборы ситуаций (Reveal),
// «делай/не делай», памятки и контрольный лист в конце главы.
// Иллюстраций к этой теме нет, поэтому `asset: ''`.
//
// Мультиклиентность: НИКАКИХ имён людей, названий станций и цифр
// конкретного предприятия в качестве правила. Число стопов, время в
// Waiting Area, начало работы и сторона парковки — это прямо указания
// соответствующей станции, их называет тренер. Инструменты компании
// вроде учёта рабочего времени приводятся только как пример
// («например, Kenjo»). Конкретными могут оставаться: инструменты Amazon
// (Flex, Mentor, ATLAS, Scorecard), приложение CoDriver, правила
// перерывов по § 4 ArbZG и Green Book по § 1 Abs. 6 FPersV — всё это
// действует одинаково на любом предприятии.

