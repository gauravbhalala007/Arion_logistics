// lib/data/driver_profile/driver_profile_history_texts.dart
//
// Texte der beiden neuen Fahrerprofil-Sektionen:
//   * „Deine Fahrhistorie" / „Your driving history"  (Vorfälle)
//   * „Deine Anwesenheit"  / „Your attendance"       (Überstunden,
//     Krankmeldungen, Urlaub)
//
// Aufbau und Fallback-Kette bewusst identisch zu den übrigen
// Fahrer-Inhalten (`privacy_camera_texts.dart`, `green_book_texts.dart`):
// eine `const Map<String, String>` je Sprache, ein Lookup mit
// `locale -> en -> key`. Damit erscheinen beide Sektionen in genau den
// elf Sprachen, die `AppLocalizations.supportedLocales` führt, ohne dass
// ein zweites Übersetzungssystem entsteht.
//
// Bewusst NICHT in `app_localizations.dart`: dort leben `bg` und `es` in
// getrennten Flat-Dateien, neue Keys müssten also an drei Stellen
// gepflegt werden. Hier steht jede Sprache an einer Stelle.

/// Text-Lookup mit Fallback `locale -> en -> key`.
///
/// `languageCode` darf ein Region-Subtag tragen (`de_DE`, `de-AT`) — er
/// wird abgeschnitten. `vars` ersetzt Platzhalter der Form `{key}`.
String driverProfileHistoryText(
  String languageCode,
  String key, {
  Map<String, String>? vars,
}) {
  final lang = languageCode.trim().toLowerCase().split(RegExp('[-_]')).first;
  final table = _tables[lang] ?? _en;
  var out = table[key] ?? _en[key] ?? key;
  if (vars != null) {
    for (final entry in vars.entries) {
      out = out.replaceAll('{${entry.key}}', entry.value);
    }
  }
  return out;
}

/// Monatsname (1..12) in der Fahrersprache. Handgepflegt, weil
/// `initializeDateFormatting` in dieser App nicht läuft und
/// `DateFormat.yMMMM(locale)` deshalb nur `en_US` beherrscht.
String driverProfileMonthName(String languageCode, int month) {
  final names = driverProfileHistoryText(
    languageCode,
    'month_names',
  ).split(',');
  if (month < 1 || month > names.length) return month.toString();
  return names[month - 1].trim();
}

